import { requireHealer } from "@/lib/auth/session";
import {
  getRules, getBookingSettings, getExceptions, getAvailability,
} from "@/lib/services/availability";
import { ScheduleEditor } from "@/components/healer/schedule-editor";
import { BookingRulesForm } from "@/components/healer/booking-rules-form";
import { ExceptionsManager } from "@/components/healer/exceptions-manager";
import {
  WEEKDAYS, normaliseTime, type WeeklySchedule,
} from "@/lib/booking/schedule";
import { toDateKey } from "@/lib/booking/window";

export const metadata = { title: "Availability · HealerJi" };
export const dynamic = "force-dynamic";

/**
 * The availability page.
 *
 * Reads the healer's real rows, hands them to the editor, and — importantly —
 * runs the SAME slot generator the public booking calendar uses to show what a
 * customer would actually see tomorrow. That preview is not a mock: it is a call
 * to get_available_slots, so if it is wrong here it is wrong publicly, and the
 * healer finds out before a customer does.
 */
export default async function HealerAvailabilityPage() {
  const viewer = await requireHealer();

  const today = new Date();
  const rangeEnd = new Date(today);
  rangeEnd.setDate(rangeEnd.getDate() + 120);

  const [rules, settings, exceptions] = await Promise.all([
    getRules(viewer.healerId),
    getBookingSettings(viewer.healerId),
    getExceptions(viewer.healerId, toDateKey(today), toDateKey(rangeEnd)),
  ]);

  // Group the flat rule rows into the shape the editor works in.
  const schedule: WeeklySchedule = WEEKDAYS.map((day) => ({
    weekday: day.value,
    ranges: (rules.ok ? rules.data : [])
      .filter((r) => r.weekday === day.value)
      .map((r) => ({ start: normaliseTime(r.start_time), end: normaliseTime(r.end_time) }))
      .sort((a, b) => a.start.localeCompare(b.start)),
  }));

  // What a customer would see for tomorrow, via the public slot generator.
  const previewDate = new Date(today);
  previewDate.setDate(previewDate.getDate() + 1);
  const preview = await getAvailability(
    viewer.healerSlug,
    toDateKey(previewDate),
    45
  );

  const accepting = settings.ok ? (settings.data?.accepting_bookings ?? false) : false;
  const hasRules = (rules.ok ? rules.data.length : 0) > 0;

  return (
    <>
      <header className="pb-6">
        <h1 className="font-display text-[1.75rem] leading-tight">Availability</h1>
        <p className="mt-1.5 text-sm text-ink-600 dark:text-mist-400">
          Set the hours you work. Whatever you save here is exactly what customers
          can book — nothing else opens your calendar.
        </p>
      </header>

      {!accepting || !hasRules ? (
        <div className="mb-6 rounded-lg border-l-2 border-warning-700 bg-warning-50 p-4">
          <p className="text-sm font-medium text-warning-700">
            {!hasRules
              ? "You haven't set any working hours yet."
              : "Your calendar is closed to new bookings."}
          </p>
          <p className="mt-1 text-sm text-warning-700">
            {!hasRules
              ? "Until you do, no times appear on your public profile and nobody can book you."
              : "Turn on “Accepting bookings” in Booking rules below to open it."}
          </p>
        </div>
      ) : null}

      {!rules.ok ? (
        <p role="alert" className="mb-6 rounded-sm bg-error-50 px-4 py-3 text-sm text-error-700">
          We couldn&rsquo;t load your current hours. Please reload before making
          changes, so you don&rsquo;t overwrite them with a blank week.
        </p>
      ) : (
        <section aria-labelledby="weekly-heading">
          <h2 id="weekly-heading" className="sr-only">Weekly schedule</h2>
          <ScheduleEditor initial={schedule} />
        </section>
      )}

      {/* -------------------------------------------------- live preview */}
      <section
        aria-labelledby="preview-heading"
        className="mt-10 rounded-lg bg-white p-5 shadow-e-1 dark:bg-night-900"
      >
        <h2 id="preview-heading" className="font-display text-[1.0625rem]">
          What customers see tomorrow
        </h2>
        <p className="mt-1 text-sm text-ink-600 dark:text-mist-400">
          Generated by the same engine as the public booking page, for a
          45-minute session.
        </p>

        {!preview.ok ? (
          <p className="mt-4 text-sm text-mist-500">Preview unavailable just now.</p>
        ) : preview.data.slots.length === 0 ? (
          <p className="mt-4 text-sm text-mist-500">
            {preview.data.unconfigured
              ? "No times tomorrow — either that weekday is closed or the day is blocked."
              : "No times left tomorrow; everything is booked."}
          </p>
        ) : (
          <>
            <p className="mt-3 text-sm">
              <span className="font-medium tabular-nums">{preview.data.slots.length}</span> open times
            </p>
            <ul className="mt-3 flex flex-wrap gap-2">
              {preview.data.slots.slice(0, 24).map((slot) => (
                <li
                  key={slot.id}
                  className="rounded-full bg-surface-50 px-3 py-1.5 text-sm tabular-nums dark:bg-night-950"
                >
                  {slot.label}
                </li>
              ))}
            </ul>
          </>
        )}
      </section>

      {/* -------------------------------------------------- booking rules */}
      <section
        aria-labelledby="rules-heading"
        className="mt-6 rounded-lg bg-white p-5 shadow-e-1 dark:bg-night-900"
      >
        <h2 id="rules-heading" className="font-display text-[1.0625rem]">Booking rules</h2>
        <p className="mt-1 text-sm text-ink-600 dark:text-mist-400">
          How your open hours are turned into bookable times.
        </p>
        <div className="mt-5">
          <BookingRulesForm settings={settings.ok ? settings.data : null} />
        </div>
      </section>

      {/* ---------------------------------------------------- exceptions */}
      <section
        aria-labelledby="exceptions-heading"
        className="mt-6 rounded-lg bg-white p-5 shadow-e-1 dark:bg-night-900"
      >
        <h2 id="exceptions-heading" className="font-display text-[1.0625rem]">
          Holidays &amp; one-off changes
        </h2>
        <p className="mt-1 text-sm text-ink-600 dark:text-mist-400">
          Block specific dates, or open hours you don&rsquo;t normally work.
        </p>
        <div className="mt-5">
          <ExceptionsManager exceptions={exceptions.ok ? exceptions.data : []} />
        </div>
      </section>
    </>
  );
}
